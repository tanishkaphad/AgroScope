const LANGUAGES = { en, mr, hi };

export function getText(lang) {
  return { ...en, ...LANGUAGES[lang] };
}

// Digits stay Latin in every language, so figures match the reports.
export function formatNumber(value) {
  return Number(value).toLocaleString('en-US', { maximumFractionDigits: 1 });
}

export function formatDate(isoDate, lang) {
  const locale = { en: 'en-IN', mr: 'mr-IN-u-nu-latn', hi: 'hi-IN-u-nu-latn' }[lang] ?? 'en-IN';
  return new Date(`${isoDate}T00:00:00`).toLocaleDateString(locale, { day: 'numeric', month: 'long', year: 'numeric' });
}

export function errorText(message, t) {
  return message === API_UNREACHABLE ? t.apiUnreachable : message;
}
